-- Estructura de la base del gimnasio. `gym_db` se reemplaza por DB_NAME al instalar.
CREATE DATABASE IF NOT EXISTS gym_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE gym_db;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS asistencias, cuotas, turnos, inscripciones, socios, horarios, planes, usuarios;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE usuarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  clave_hash VARCHAR(100) NOT NULL,
  rol ENUM('admin') NOT NULL DEFAULT 'admin',
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE planes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  descripcion VARCHAR(200) NULL,
  precio DECIMAL(10,2) NOT NULL,
  clases_por_semana TINYINT UNSIGNED NULL COMMENT 'NULL = pase libre',
  beneficios TEXT NULL COMMENT 'Uno por línea',
  destacado TINYINT(1) NOT NULL DEFAULT 0,
  activo TINYINT(1) NOT NULL DEFAULT 1,
  orden SMALLINT NOT NULL DEFAULT 0,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- Grilla semanal. dia: 1 = lunes … 7 = domingo
CREATE TABLE horarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  actividad VARCHAR(60) NOT NULL,
  dia TINYINT UNSIGNED NOT NULL,
  hora_inicio TIME NOT NULL,
  hora_fin TIME NOT NULL,
  profesor VARCHAR(80) NULL,
  cupo SMALLINT UNSIGNED NOT NULL DEFAULT 20,
  activo TINYINT(1) NOT NULL DEFAULT 1,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (dia, hora_inicio)
) ENGINE=InnoDB;

CREATE TABLE socios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  apellido VARCHAR(60) NOT NULL,
  dni VARCHAR(15) NOT NULL UNIQUE,
  email VARCHAR(120) NULL,
  telefono VARCHAR(30) NULL,
  fecha_nacimiento DATE NULL,
  plan_id INT UNSIGNED NULL,
  estado ENUM('activo','inactivo') NOT NULL DEFAULT 'activo',
  fecha_alta DATE NOT NULL,
  notas VARCHAR(300) NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE cuotas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  socio_id INT UNSIGNED NOT NULL,
  periodo CHAR(7) NOT NULL COMMENT 'AAAA-MM',
  monto DECIMAL(10,2) NOT NULL,
  vence DATE NOT NULL,
  estado ENUM('pendiente','pagada') NOT NULL DEFAULT 'pendiente',
  metodo ENUM('efectivo','transferencia','tarjeta') NULL,
  pagada_en DATETIME NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_socio_periodo (socio_id, periodo),
  FOREIGN KEY (socio_id) REFERENCES socios(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE asistencias (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  socio_id INT UNSIGNED NOT NULL,
  fecha DATE NOT NULL,
  hora TIME NOT NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_socio_dia (socio_id, fecha),
  FOREIGN KEY (socio_id) REFERENCES socios(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE turnos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  codigo CHAR(6) NOT NULL,
  horario_id INT UNSIGNED NOT NULL,
  fecha DATE NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  email VARCHAR(120) NULL,
  socio_id INT UNSIGNED NULL,
  estado ENUM('reservado','asistio','cancelado') NOT NULL DEFAULT 'reservado',
  pagado TINYINT(1) NOT NULL DEFAULT 0,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX (horario_id, fecha),
  FOREIGN KEY (horario_id) REFERENCES horarios(id) ON DELETE CASCADE,
  FOREIGN KEY (socio_id) REFERENCES socios(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE inscripciones (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  dni VARCHAR(15) NULL,
  telefono VARCHAR(30) NOT NULL,
  email VARCHAR(120) NULL,
  plan_id INT UNSIGNED NULL,
  mensaje VARCHAR(300) NULL,
  estado ENUM('nueva','contactada','convertida','descartada') NOT NULL DEFAULT 'nueva',
  socio_id INT UNSIGNED NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (plan_id) REFERENCES planes(id) ON DELETE SET NULL,
  FOREIGN KEY (socio_id) REFERENCES socios(id) ON DELETE SET NULL
) ENGINE=InnoDB;
